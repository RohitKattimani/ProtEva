import { createFileRoute } from "@tanstack/react-router";
import { ArrowUpDown, Search } from "lucide-react";
import { useMemo, useState } from "react";

import { PageHeader } from "@/components/app/AppShell";
import { Pill } from "@/components/app/StatusBadge";
import { CandidateDrawer } from "@/components/candidates/CandidateDrawer";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Skeleton } from "@/components/ui/skeleton";
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@/components/ui/select";
import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from "@/components/ui/table";
import { useCandidates, useExperiments } from "@/lib/protein/hooks";
import { isDemoMode } from "@/lib/protein/api";
import { candidateLabel } from "@/lib/protein/format";
import type { Candidate, CandidateQuery } from "@/lib/protein/types";

export const Route = createFileRoute("/candidates")({
  head: () => ({
    meta: [
      { property: "og:type", content: "website" },
      { name: "twitter:card", content: "summary_large_image" },
      { title: "Candidate library · ProtEva" },
      {
        name: "description",
        content:
          "Search, filter and compare evolved protein sequence variants across every demo experiment.",
      },
      { property: "og:title", content: "Candidate library · ProtEva" },
      {
        property: "og:description",
        content: "Search and compare evolved protein sequence variants.",
      },
    ],
  }),
  component: CandidateLibrary,
});

type SortKey = "objectiveScore" | "generation" | "diversityScore";

function CandidateLibrary() {
  const { data: experiments = [] } = useExperiments();
  const [experimentId, setExperimentId] = useState("all");
  const [generation, setGeneration] = useState("all");
  const [maxMutations, setMaxMutations] = useState("all");
  const [evaluation, setEvaluation] = useState("all");
  const [search, setSearch] = useState("");
  const [sortKey, setSortKey] = useState<SortKey>("objectiveScore");
  const [sortDesc, setSortDesc] = useState(true);
  const [selected, setSelected] = useState<Candidate | null>(null);

  const query: CandidateQuery = {
    ...(experimentId !== "all" ? { experimentId } : {}),
    ...(generation !== "all" ? { generation: Number(generation) } : {}),
    ...(maxMutations !== "all" ? { maxMutations: Number(maxMutations) } : {}),
    ...(evaluation !== "all"
      ? { evaluationStatus: evaluation as Candidate["evaluationStatus"] }
      : {}),
    ...(search ? { search } : {}),
  };
  const { data = [], isLoading, isError, error } = useCandidates(query);

  const rows = useMemo(
    () =>
      [...data].sort((a, b) => {
        const av = a[sortKey] ?? -1;
        const bv = b[sortKey] ?? -1;
        return sortDesc ? Number(bv) - Number(av) : Number(av) - Number(bv);
      }),
    [data, sortKey, sortDesc],
  );

  const experimentNames = useMemo(
    () => new Map(experiments.map((experiment) => [experiment.id, experiment.name])),
    [experiments],
  );

  return (
    <div className="space-y-5">
      <PageHeader
        title="Candidate library"
        description={
          isDemoMode
            ? "Every variant generated by the genetic algorithm across demo experiments. Scores are illustrative."
            : "Every candidate persisted by your experiments. Scores are the recorded ProteinMPNN target-preference proxy; diversity is not evaluated in live screening."
        }
      />

      <div className="flex flex-wrap items-center gap-2">
        <div className="relative">
          <Search className="pointer-events-none absolute left-2.5 top-1/2 size-3.5 -translate-y-1/2 text-muted-foreground" />
          <Input
            value={search}
            onChange={(e) => setSearch(e.target.value)}
            placeholder="Candidate ID or mutation (e.g. A42V)"
            className="h-9 w-64 bg-surface pl-8"
          />
        </div>
        <Select value={experimentId} onValueChange={setExperimentId}>
          <SelectTrigger className="h-9 w-56 bg-surface">
            <SelectValue placeholder="Experiment" />
          </SelectTrigger>
          <SelectContent>
            <SelectItem value="all">All experiments</SelectItem>
            {experiments.map((experiment) => (
              <SelectItem key={experiment.id} value={experiment.id}>
                {experiment.id} · {experiment.name}
              </SelectItem>
            ))}
          </SelectContent>
        </Select>
        <Select value={generation} onValueChange={setGeneration}>
          <SelectTrigger className="h-9 w-36 bg-surface">
            <SelectValue placeholder="Generation" />
          </SelectTrigger>
          <SelectContent>
            <SelectItem value="all">All generations</SelectItem>
            {Array.from({ length: 12 }).map((_, i) => (
              <SelectItem key={i + 1} value={String(i + 1)}>
                Generation {i + 1}
              </SelectItem>
            ))}
          </SelectContent>
        </Select>
        <Select value={maxMutations} onValueChange={setMaxMutations}>
          <SelectTrigger className="h-9 w-40 bg-surface">
            <SelectValue placeholder="Mutations" />
          </SelectTrigger>
          <SelectContent>
            <SelectItem value="all">Any mutation count</SelectItem>
            {[1, 2, 3, 4, 6].map((n) => (
              <SelectItem key={n} value={String(n)}>
                ≤ {n} substitutions
              </SelectItem>
            ))}
          </SelectContent>
        </Select>
        <Select value={evaluation} onValueChange={setEvaluation}>
          <SelectTrigger className="h-9 w-40 bg-surface">
            <SelectValue placeholder="Evaluation" />
          </SelectTrigger>
          <SelectContent>
            {["all", "pending", "screening", "evaluated", "rejected"].map((value) => (
              <SelectItem key={value} value={value} className="capitalize">
                {value}
              </SelectItem>
            ))}
          </SelectContent>
        </Select>
        <Select value={sortKey} onValueChange={(v) => setSortKey(v as SortKey)}>
          <SelectTrigger className="h-9 w-44 bg-surface">
            <SelectValue />
          </SelectTrigger>
          <SelectContent>
            <SelectItem value="objectiveScore">Sort by score</SelectItem>
            <SelectItem value="generation">Sort by generation</SelectItem>
            {isDemoMode && <SelectItem value="diversityScore">Sort by diversity</SelectItem>}
          </SelectContent>
        </Select>
        <Button variant="outline" size="sm" onClick={() => setSortDesc((v) => !v)}>
          <ArrowUpDown className="size-4" /> {sortDesc ? "Desc" : "Asc"}
        </Button>
      </div>

      {isError ? (
        <Card className="border-destructive/40 bg-destructive/5">
          <CardHeader>
            <CardTitle className="text-base">Could not load candidates</CardTitle>
            <CardDescription>{(error as Error).message}</CardDescription>
          </CardHeader>
        </Card>
      ) : (
        <Card>
          <CardContent className="px-0">
            {isLoading ? (
              <div className="space-y-2 p-4">
                <Skeleton className="h-10" />
                <Skeleton className="h-10" />
              </div>
            ) : rows.length === 0 ? (
              <p className="p-10 text-center text-sm text-muted-foreground">
                No candidates match these filters.
              </p>
            ) : (
              <div className="max-h-[60vh] overflow-auto">
                <Table>
                  <TableHeader className="sticky top-0 bg-card">
                    <TableRow>
                      <TableHead>Candidate</TableHead>
                      <TableHead>Experiment</TableHead>
                      <TableHead>Parent</TableHead>
                      <TableHead>Gen.</TableHead>
                      <TableHead>Mutations</TableHead>
                      <TableHead className="hidden lg:table-cell">Sequence</TableHead>
                      <TableHead className="text-right">Score</TableHead>
                      {isDemoMode && <TableHead className="text-right">Diversity</TableHead>}
                      <TableHead>Audit</TableHead>
                    </TableRow>
                  </TableHeader>
                  <TableBody>
                    {rows.slice(0, 300).map((candidate) => (
                      <TableRow
                        key={`${candidate.experimentId}:${candidate.id}`}
                        className="cursor-pointer"
                        onClick={() => setSelected(candidate)}
                      >
                        <TableCell className="font-mono text-xs">
                          {candidateLabel(candidate)}
                        </TableCell>
                        <TableCell
                          className="max-w-40 truncate text-xs text-muted-foreground"
                          title={candidate.experimentId}
                        >
                          {experimentNames.get(candidate.experimentId) ?? candidate.experimentId}
                        </TableCell>
                        <TableCell className="font-mono text-[11px] text-muted-foreground">
                          {candidate.parentId ?? "wild-type"}
                        </TableCell>
                        <TableCell className="font-mono">{candidate.generation}</TableCell>
                        <TableCell className="font-mono text-xs text-primary">
                          {candidate.mutations.slice(-3).join(", ") || "—"}
                        </TableCell>
                        <TableCell className="hidden max-w-48 truncate font-mono text-[11px] text-muted-foreground lg:table-cell">
                          {candidate.sequence.slice(0, 28)}…
                        </TableCell>
                        <TableCell className="text-right font-mono tabular-nums">
                          {candidate.objectiveScore?.toFixed(3) ?? "—"}
                        </TableCell>
                        {isDemoMode && (
                          <TableCell className="text-right font-mono tabular-nums">
                            {candidate.diversityScore?.toFixed(2) ?? "—"}
                          </TableCell>
                        )}
                        <TableCell>
                          <Pill
                            tone={
                              candidate.auditStatus === "flagged"
                                ? "warning"
                                : candidate.auditStatus === "confirmed"
                                  ? "success"
                                  : "muted"
                            }
                          >
                            {candidate.auditStatus}
                          </Pill>
                        </TableCell>
                      </TableRow>
                    ))}
                  </TableBody>
                </Table>
              </div>
            )}
          </CardContent>
        </Card>
      )}

      <CandidateDrawer candidate={selected} onOpenChange={(open) => !open && setSelected(null)} />
    </div>
  );
}
